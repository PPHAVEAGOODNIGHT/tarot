def sign_of(pos):
    """'狮子10°23'' -> (星座, 度数串)"""
    SIGNS = ["白羊", "金牛", "双子", "巨蟹", "狮子", "处女",
             "天秤", "天蝎", "射手", "摩羯", "水瓶", "双鱼"]
    if not pos:
        return "", ""
    for s in SIGNS:
        if pos.startswith(s):
            return s, pos[len(s):]
    return pos[:2], pos[2:]


