# 三种合成句式，按组合轮换，避免九张卡读起来一个腔调
_COMBO_TPL = [
    "{sg}座给的是手法——{style}。落在第{hn}宫，就是你拿这套手法去打「{hkey}」这场仗。"
    "所以在这块事上，你从来不是直来直去地要，总得{style}，绕这么一圈才落地。",

    "{sg}座的手法，加上第{hn}宫这块地，凑成你在「{hkey}」上最真实的反应：{style}。"
    "别人看着觉得你在这儿别扭，其实你只会这么来，换个走法你自己先撑不住。",

    "这股劲压在第{hn}宫，跑法却是{sg}座那一套：{style}。"
    "结果就是「{hkey}」这块你做得成，但每回做完，自己都得先缓一口气才算完。",
]

_ASC_COMBO = ("你对外亮出来的门面，就是「{hkey}」这块地的样子：{style}。"
              "所以别人第一眼看到的你，跟真实的你之间总有点错位——不是装的，是你只会这么出场。")


def combo_text(planet, sign, house):
    """星座 + 宫位 组合含义：拿星座的手法，去打宫位这块地"""
    try:
        house = int(house)
    except (TypeError, ValueError):
        house = 0
    if not house:
        return ""
    hkey = HOUSE_KEY.get(house, "")
    style = SIGN_STYLE.get(sign, "")
    if not hkey or not style:
        return ""
    if planet == "上升":
        return _ASC_COMBO.format(style=style, hkey=hkey)
    tpl = _COMBO_TPL[(house + len(planet or "") + len(sign or "")) % len(_COMBO_TPL)]
    return tpl.format(sg=sign, style=style, hn=house, hkey=hkey)
